#!/usr/bin/env python3
"""Input script "JE_SFCodes combos" for ship 1
(`varz.c:shipCombos[1] = {1, 2, 0}`): Invulnerability (`keyboardCombos[0]`
= down, up, down, up+fire) and Atom Bomb (`keyboardCombos[1]` = right,
left, down, up+fire), plus the reversed sequences (failures and resets
of `SFCurrentCode`). Bits (ADR 0006): 1 up, 2 down, 4 left,
8 right, 0x10 fire."""

U, D, L, R, F = 1, 2, 4, 8, 0x10
seqs = [[D, U, D, U | F], [U, D, U, D | F], [R, L, D, U | F], [L, R, U, D | F]]
print("# JE_SFCodes combos of ship 1 (generated by make_sf_combo.py)")
for _ in range(600):
    for s in seqs:
        for m in s:
            print(3, f"{m:02x}")
        print(10, "00")
