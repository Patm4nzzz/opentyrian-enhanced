#!/usr/bin/env python3
"""Input script "fire + pulsed sidekicks": ammo sidekicks only
fire on their key (`player_movement.c:JE_playerMovement`,
`button[1 + i] && ammo > 0`). Bits (ADR 0006): 1 up, 2 down, 4 left,
8 right, 0x10 fire, 0x40 left sidekick, 0x80 right sidekick."""

pattern = [
    (25, 0xD4),
    (8, 0x00),
    (25, 0xD8),
    (8, 0x00),
    (12, 0x51),
    (8, 0x00),
    (12, 0x92),
    (8, 0x00),
]
print("# fire + pulsed sidekicks (generated by make_sidekick_fire.py)")
for _ in range(200):
    for ticks, mask in pattern:
        print(ticks, f"{mask:02x}")
