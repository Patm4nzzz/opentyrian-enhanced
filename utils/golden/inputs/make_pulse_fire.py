#!/usr/bin/env python3
"""Input script "pulsed fire": releases fire regularly so that
`varz.c:JE_doSpecialShot` re-triggers the special weapon (fireButtonHeld goes back
to false). Bits (ADR 0006): 1 up, 2 down, 4 left, 8 right, 0x10 fire."""

pattern = [
    (25, 0x14),
    (8, 0x00),
    (25, 0x18),
    (8, 0x00),
    (12, 0x11),
    (8, 0x00),
    (12, 0x12),
    (8, 0x00),
]
print("# pulsed fire, left/right/up/down (generated by make_pulse_fire.py)")
for _ in range(200):
    for ticks, mask in pattern:
        print(ticks, f"{mask:02x}")
